import * as React from "react"

import { cn } from "@/lib/utils"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        // 圆角、底色、边框与阴影全部读 --nf-card-*：五套主题各有自己的纸面纹理、边饰与材质高光，
        // 卡片内缘装饰层（装订虚线 / 典籍压线 / 朱砂双线 / 瓷釉高光）由 styles/novelfork-motifs.css 的 ::before 画出。
        "group/card relative flex flex-col gap-4 overflow-hidden rounded-[var(--nf-card-radius,var(--radius-lg))] border border-[var(--nf-card-border,var(--border))] bg-card py-4 text-sm text-card-foreground has-data-[slot=card-footer]:pb-0 has-[>img:first-child]:pt-0 data-[size=sm]:gap-3 data-[size=sm]:py-3 data-[size=sm]:has-data-[slot=card-footer]:pb-0 *:[img:first-child]:rounded-t-[var(--nf-card-radius,var(--radius-lg))] *:[img:last-child]:rounded-b-[var(--nf-card-radius,var(--radius-lg))]",
        className
      )}
      {...props}
    />
  )
}


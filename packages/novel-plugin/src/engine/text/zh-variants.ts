const TRADITIONAL_TO_SIMPLIFIED: ReadonlyMap<string, string> = (() => {
  const map = new Map<string, string>();
  const chars = [...TRADITIONAL_SIMPLIFIED_PAIRS];
  for (let index = 0; index + 1 < chars.length; index += 2) {
    const traditional = chars[index]!;
    const simplified = chars[index + 1]!;
    if (traditional !== simplified) map.set(traditional, simplified);
  }
  return map;
})();

/** 单字繁 → 简；表外的字原样返回。输入输出都是一个码点。 */
export function toSimplifiedChar(char: string): string {
  return TRADITIONAL_TO_SIMPLIFIED.get(char) ?? char;
}

/** 逐字繁 → 简，长度（码点数）不变。 */
export function toSimplifiedText(text: string): string {
  let result = "";
  for (const char of text) result += toSimplifiedChar(char);
  return result;
}

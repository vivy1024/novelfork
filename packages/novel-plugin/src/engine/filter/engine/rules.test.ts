describe("AI taste filter rules", () => {
  for (const rule of FILTER_RULES) {
    it(`${rule.id} detects positive cases and ignores negative cases`, () => {
      for (const text of positiveCases[rule.id] ?? []) {
        const hit = rule.run(text, { text, tokenized: undefined as never, priorHits: [] });
        expect(hit?.spans.length ?? 0, `${rule.id} positive: ${text}`).toBeGreaterThan(0);
      }
      for (const text of negativeCases[rule.id] ?? []) {
        const hit = rule.run(text, { text, tokenized: undefined as never, priorHits: [] });
        expect(hit, `${rule.id} negative: ${text}`).toBeNull();
      }
    });
  }

  it("maps score levels at boundaries", () => {
    expect(mapAiTasteLevel(29)).toBe("clean");
    expect(mapAiTasteLevel(30)).toBe("mild");
    expect(mapAiTasteLevel(50)).toBe("moderate");
    expect(mapAiTasteLevel(71)).toBe("severe");
  });

  it("scores human-like fixture below 30 and GPT-like fixture above 50 within 200ms", async () => {
    // 人类样本必须是真实的连续正文，不能用 `.repeat()` 拼长 —— 重复文本的
    // 双字搭配去重率天然极低，会被 r17（词汇丰富度）正确判为词池循环，
    // 那是 fixture 不真实，不是规则误报。
    const humanText = [
      "韩立把药锄扛在肩上，鞋底沾着泥。他没急着回屋，先蹲在田埂边，捻起一点发黑的土。风从山口钻下来，吹得灯笼乱晃。老仆问他要不要添饭，他摇头，只说炉火别灭。",
      "灶房里传来锅铲刮底的声音。他站起身，膝盖发出一声轻响，那是去年冬天在药谷里跪太久留下的。院子里晒着七八张竹筛，最边上那张翻了，几株半干的灵草掉在地上，被踩得只剩梗。",
      "他弯腰把它们捡起来，一根根摆回筛子。手指上有土，抹在灵草上，那点黄色的花蕊就糊了。",
      "“这批还能用吗。”老仆在门口问。",
      "“卖不出价。”",
      "“那就自己留着。”",
      "院墙外有人走过，脚步很重，踩过水洼时溅了一声。韩立抬头看一眼，墙头只有一片天，灰的，压得很低。要下雨了。",
      "炉子上的药罐咕嘟响着，盖沿溢出白汽。他掀开盖，汤色发浑，比昨天差一截。火候不对，也可能那味主药本来就旧。",
      "雨终于落下来，先是零星几点，很快连成片，砸在瓦上像有人一直在敲门。",
    ].join("\n\n");
    const gptText = "首先，我们需要明确人物目标。其次，值得注意的是，以下是为您生成的章节内容。总的来说，这一段文字非常精彩、十分重要、极其动人。最后，让我们一起来进入这个宏大壮阔璀璨夺目的世界。".repeat(30);

    const human = await runFilter(humanText);
    const gpt = await runFilter(gptText);

    expect(human.aiTasteScore).toBeLessThan(30);
    expect(gpt.aiTasteScore).toBeGreaterThan(50);
    expect(gpt.elapsedMs).toBeLessThan(200);
  });

  it("treats external scores as manual-review evidence, not a platform conclusion", async () => {
    const report = await runFilter("韩立把药锄扛在肩上。", {
      zhuqueConfig: {
        apiKey: "key",
        endpoint: "https://zhuque.local/scan",
        fetchImpl: vi.fn().mockResolvedValue({ ok: true, json: async () => ({ score: 42 }) }),
      },
    });

    expect(report.crossSpecHints).toEqual([expect.objectContaining({
      type: "external-ai-signal",
      message: expect.stringContaining("42/100"),
      data: { zhuqueScore: 42 },
    })]);
    expect(report.crossSpecHints?.[0]?.message).toContain("人工复核");
    expect(report.crossSpecHints?.[0]?.message).not.toContain("拒稿");
  });
});
